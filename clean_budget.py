def _norm_text(v: str, col: str) -> str:
    """ล้าง artifact ระดับตัวอักษร (ทำกับทุกคอลัมน์ข้อความ)"""
    if v == "":
        return v
    v = unicodedata.normalize("NFC", v)

    # ลำดับเครื่องหมายไทย: ำ+tone → tone+ำ ; ์+สระล่าง → สระล่าง+์
    v = re.sub("\u0e33([\u0e48\u0e49\u0e4a\u0e4b])", lambda m: m.group(1) + "\u0e33", v)
    v = re.sub("\u0e4c([\u0e38\u0e39\u0e34\u0e35\u0e36\u0e37\u0e47])",
               lambda m: m.group(1) + "\u0e4c", v)

    # ไม้ยมก: เว้นวรรคหน้า-หลัง ตามหลักราชบัณฑิต
    v = re.sub(r"(?<=\S)\s*ๆ", " ๆ", v)
    v = re.sub(r"ๆ(?=\S)", "ๆ ", v)

    # '=' คือ OCR ของขีดกลางในชื่อเส้นทาง (เช่น "สายเชียงใหม่ = เชียงราย")
    # รหัสเส้นทาง (มีตัวเลขสองข้าง เช่น "พล.ถ.2 = 0520") → ต่อด้วยขีดกลางไม่เว้นวรรค
    v = re.sub(r"(?<=[\d.])[ \t]*=[ \t]*(?=[\d.])", "-", v)
    # รหัสเส้นทางที่มีตัวเลข/จุดสองข้าง (เช่น "พล.ถ.2 = 0520") → ต่อด้วยขีดกลางไม่เว้นวรรค
    v = re.sub(r"(?<=[\d.])[ \t]*=[ \t]*(?=[\d.])", "-", v)
    v = re.sub(r"\s*=\s*", " - ", v)
    # เศษขีดกลางท้ายข้อความจาก artifact ของตาราง ("... กรุงเทพมหานคร = บาท")
    v = re.sub(r"\s+-\s+บาท$", "", v)
    v = re.sub(r"\s+-\s*$", "", v)
    # NOTE: ไม่ปรับช่องว่างรอบ '-' ระหว่างอักษรไทย เพราะจะไปทำลายชื่อเฉพาะ
    # เช่น "เทศบาลเมืองสุไหงโก-ลก" — ค่าที่ต่างกันแค่ '-' ถูกจัดการในขั้น auto-skeleton แล้ว

    # จุดซ้อน/จุดเกินจาก PDF ("บ..ใหม่มงคล", "พ.ศ. ....")
    # ต้องลบช่องว่างก่อนจุด "ก่อน" ยุบจุดซ้อน ไม่งั้น "พ.ศ. ...." จะกลายเป็น "พ.ศ.."
    v = re.sub(r"\s+\.", ".", v)
    for _ in range(2):
        v = re.sub(r"\.{2,}", ".", v)

    # ข้อความซ้ำทั้งวลี (ทั้ง cell เป็น A + " " + A)
    for _ in range(3):
        m = re.match(r"^(.{6,}?)\s+\1$", v)
        if not m:
            break
        v = m.group(1)
    # วลีซ้ำติดกัน (เฉพาะ PROJECT/OUTPUT ที่พบว่า PDF ทำข้อความซ้ำ)
    if col in ("PROJECT", "OUTPUT"):
        toks = v.split(" ")
        out = []
        for t in toks:
            if out and t == out[-1] and len(t) >= 8:
                continue
            out.append(t)
        v = " ".join(out)

    # วงเล็บ
    while v.count(")") > v.count("(") and v.endswith(")"):
        v = v[:-1].rstrip()
    if v.count("(") > v.count(")"):
        v = v + ")" * (v.count("(") - v.count(")"))

    # ช่องว่างซ้อน + ช่องว่างรอบวงเล็บ
    v = re.sub(r"\s+", " ", v)
    v = re.sub(r"\(\s+", "(", v)
    v = re.sub(r"\s+\)", ")", v)
    v = v.strip()

    # " บาท" เกินท้ายค่าหมวดงบ (artifact ของตารางต้นทาง)
    if col.startswith("CATEGORY_LV") and col != "CATEGORY_LV1":
        v = re.sub(r"\s+บาท$", "", v)
    return v


def _skeleton(v: str) -> str:
    """เทียบเฉพาะ 'แก่น' ของข้อความ: ตัดช่องว่าง/เครื่องหมายวรรคตอนออก"""
    return re.sub(r"[\s\(\)\[\]\.,'\"“”‘’·•\-\u2013\u2014/\u0e2f+]+", "", v)


def step_normalize(df) -> None:
    note("\n=== ขั้น 1f: ล้าง artifact ระดับตัวอักษร (ทุกคอลัมน์ข้อความ) ===")
    for c in TEXT_COLS:
        before = df[c].copy()
        df[c] = df[c].map(lambda v, col=c: _norm_text(v, col))
        n = int((before != df[c]).sum())
        if n:
            note(f"  {c}: แก้ {n:,} cell")
            audit2.append((c, "normalize", "(artifact ตัวอักษร/วรรคตอน)", "(รูปแบบมาตรฐาน)", n))

    for frm, to, scope in SUBSTR_RULES2:
        cols = [scope] if scope else TEXT_COLS
        for c in cols:
            n = int(df[c].str.contains(re.escape(frm), regex=True).sum())
            if n:
                df[c] = df[c].str.replace(re.escape(frm), to, regex=True)
                note(f"  [{c}] {frm} -> {to}: {n:,} cell")
                audit2.append((c, "substring2", frm, to, n))

    for pat, rep, scope in REGEX_RULES2:
        cols = [scope] if scope else TEXT_COLS
        for c in cols:
            n = int(df[c].str.contains(pat, regex=True).sum())
            if n:
                df[c] = df[c].str.replace(pat, rep, regex=True)
                note(f"  [{c}] regex {pat.pattern}: {n:,} cell")
                audit2.append((c, "regex2", pat.pattern, rep, n))


def step_column_canon(df) -> None:
    note("\n=== ขั้น 1g: รวมค่าเดียวกันที่สะกดต่าง (รายคอลัมน์) ===")
    for c, mapping in COLUMN_CANON.items():
        for frm, to in mapping.items():
            m = df[c] == frm
            n = int(m.sum())
            if n:
                df.loc[m, c] = to
                kind = "canon"
                audit2.append((c, kind, frm, to, n))
        note(f"  {c}: {len(mapping)} คู่ mapping")

    # รวมค่าแบบ "ต่างกันแค่ช่องว่าง/เครื่องหมาย" ในคอลัมน์ที่ใช้ group-by
    note("\n  -- auto-merge ค่าที่ต่างกันแค่ช่องว่าง/เครื่องหมายวรรคตอน --")
    for c in GROUP_COLS:
        counts = df[c][df[c] != ""].value_counts()
        groups = {}
        for val in counts.index:
            groups.setdefault(_skeleton(val), []).append(val)
        merged = 0
        for key, vals in groups.items():
            if len(vals) < 2:
                continue
            vals = sorted(vals, key=lambda v: -counts[v])
            canon = vals[0]
            for v in vals[1:]:
                m = df[c] == v
                n = int(m.sum())
                df.loc[m, c] = canon
                audit2.append((c, "auto-skeleton", v, canon, n))
                merged += n
        if merged:
            note(f"  {c}: รวม {merged:,} cell")


