def count_cells(df, col, pattern):
    if isinstance(pattern, re.Pattern):
        return int(df[col].str.contains(pattern).sum())
    return int((df[col] == pattern).sum())


def main():
    import os
    os.makedirs(OUTDIR, exist_ok=True)

    note(f"=== อ่านข้อมูลต้นฉบับ {SRC} ===")
    df = pd.read_csv(SRC, dtype=str, keep_default_na=False)
    n_raw = len(df)
    note(f"แถว: {n_raw:,}  คอลัมน์: {df.shape[1]}")
    raw_total_by_year = df.assign(
        _a=pd.to_numeric(df["AMOUNT"]), _y=pd.to_numeric(df["FISCAL_YEAR"]
    )).groupby("_y")["_a"].sum()

    text_cols = list(df.columns)

    # ---------- ขั้น 0: strip whitespace ----------
    for c in text_cols:
        df[c] = df[c].str.strip()

    # ---------- ขั้น 1a: exact cell fixes ----------
    note("\n=== ขั้น 1a: exact cell mapping (คำสะกดผิดทั้ง cell) ===")
    for col, mapping in EXACT_FIXES.items():
        n = 0
        for frm, to in mapping.items():
            m = df[col] == frm
            n += int(m.sum())
            df.loc[m, col] = to
        if mapping:
            note(f"  {col}: {len(mapping)} รูปแบบ -> {n:,} cell")
            fix_audit.append(("exact", col, f"{len(mapping)} mappings", n))

    # ---------- ขั้น 1b: artifact rules ----------
    note("\n=== ขั้น 1b: artifact rules (OCR/แปลงข้อมูล) ===")
    for name, pat, rep in ARTIFACT_RULES:
        tot = 0
        for c in text_cols:
            n = int(df[c].str.contains(pat, regex=True).sum())
            if n:
                df[c] = df[c].str.replace(pat, rep, regex=True)
                tot += n
        note(f"  {name}: {tot:,} cells")
        fix_audit.append(("artifact", "ALL", name, tot))

    # ---------- ขั้น 1c: substring rules ----------
    note("\n=== ขั้น 1c: substring rules (คำสะกดผิดบางส่วน) ===")
    tot_rules = 0
    for frm, to, scope, _note in SUBSTR_RULES:
        cols = [scope] if scope else text_cols
        tot = 0
        for c in cols:
            n = int(df[c].str.contains(re.escape(frm), regex=True).sum())
            if n:
                df[c] = df[c].str.replace(re.escape(frm), to, regex=True)
                tot += n
        if tot:
            tot_rules += 1
            fix_audit.append(("substring", scope or "ALL", f"{frm} -> {to}", tot))
    note(f"  ใช้ {tot_rules} rules")

    # ---------- ขั้น 1d: regex เสริม ----------
    for pat, rep in ITEM_REGEX_RULES:
        n = int(df["ITEM_DESCRIPTION"].str.contains(pat, regex=True).sum())
        if n:
            df["ITEM_DESCRIPTION"] = df["ITEM_DESCRIPTION"].str.replace(pat, rep, regex=True)
            fix_audit.append(("regex", "ITEM_DESCRIPTION", pat.pattern, n))
            note(f"  ITEM_DESCRIPTION regex {pat.pattern}: {n:,} cells")

    # ---------- ขั้น 1e: เติม ) ที่หายไปท้ายหน่วยงาน ----------
    m = df["BUDGETARY_UNIT"].str.endswith("(องค์การมหาชน")
    if m.sum():
        df.loc[m, "BUDGETARY_UNIT"] = df.loc[m, "BUDGETARY_UNIT"] + ")"
        note(f"\n  เติม ')' ท้าย BUDGETARY_UNIT: {int(m.sum()):,} cells")
        fix_audit.append(("rule", "BUDGETARY_UNIT", "append ')' after (องค์การมหาชน", int(m.sum())))

    # ---------- ขั้น 2: ministry mapping ----------
    note("\n=== ขั้น 2: รวมชื่อ MINISTRY ที่สะกดหลายแบบ ===")
    n_min_before = df["MINISTRY"].nunique()
    df["_ministry_inferred"] = df["MINISTRY"].isin(MINISTRY_INFERRED)  # เก็บไว้ก่อน dedup
    for frm, to in MINISTRY_MAP.items():
        n = int((df["MINISTRY"] == frm).sum())
        df.loc[df["MINISTRY"] == frm, "MINISTRY"] = to
        note(f"  {frm}  ->  {to}  ({n:,} แถว)")
    note(f"  MINISTRY ไม่ซ้ำ: ก่อน {n_min_before} -> หลัง {df['MINISTRY'].nunique()}")

    # ---------- ขั้น 3: แก้ CATEGORY_LV1 ----------
    note("\n=== ขั้น 3: แก้ CATEGORY_LV1 (คอลัมน์เลื่อน/ว่าง) ===")
    # lookup: (BUDGETARY_UNIT, ITEM_DESCRIPTION) -> valid CATEGORY_LV1 (จากแถวอื่น)
    valid = df[df["CATEGORY_LV1"].isin(VALID_CAT_LV1)]
    lookup = valid.drop_duplicates(subset=["BUDGETARY_UNIT", "ITEM_DESCRIPTION"]) \
                  .set_index(["BUDGETARY_UNIT", "ITEM_DESCRIPTION"])["CATEGORY_LV1"].to_dict()

    def fix_cat(row):
        key = (row["BUDGETARY_UNIT"], row["ITEM_DESCRIPTION"])
        return lookup.get(key, "")

    misaligned = ~df["CATEGORY_LV1"].isin(VALID_CAT_LV1 | {""})
    n_mis = int(misaligned.sum())
    if n_mis:
        df.loc[misaligned, "CATEGORY_LV1"] = df[misaligned].apply(fix_cat, axis=1)
        still_bad = misaligned & ~df["CATEGORY_LV1"].isin(VALID_CAT_LV1)
        note(f"  คอลัมน์เลื่อน (มีชื่อแผนงานในช่องหมวดงบ): {n_mis} แถว -> เติมจากปีอื่นได้ "
             f"{int((misaligned & df['CATEGORY_LV1'].isin(VALID_CAT_LV1)).sum()):,} แถว, เหลือว่าง {int(still_bad.sum())} แถว")
    blank1 = df["CATEGORY_LV1"] == ""
    n_blank = int(blank1.sum())
    df.loc[blank1, "CATEGORY_LV1"] = df[blank1].apply(fix_cat, axis=1)
    filled = blank1 & df["CATEGORY_LV1"].isin(VALID_CAT_LV1)
    note(f"  CATEGORY_LV1 ว่าง: {n_blank} แถว -> เติมจากปีอื่นได้ {int(filled.sum()):,} แถว, เหลือว่าง {int((blank1 & ~filled).sum())} แถว")

    # ---------- ขั้น 4: dedup ----------
    note("\n=== ขั้น 4: ลบแถวซ้ำซ้อน ===")
    n_dup = int(df.duplicated().sum())
    df = df.drop_duplicates().reset_index(drop=True)
    dup_amt = None
    note(f"  ลบแถวซ้ำ: {n_dup} แถว -> เหลือ {len(df):,} แถว")

    # ---------- ขั้น 5+6: flags, เติมค่า, แยกไฟล์, แปลงชนิด ----------
    note("\n=== ขั้น 5-6: flag / เติมค่า / แยกภาระผูกพัน / แปลงชนิดข้อมูล ===")
    flags = pd.Series([[] for _ in range(len(df))], index=df.index)

    def add_flag(mask, name):
        flags[mask] = flags[mask].map(lambda lst: lst + [name] if name not in lst else lst)

    df["AMOUNT_num"] = pd.to_numeric(df["AMOUNT"], errors="coerce")
    df["YEAR_num"] = pd.to_numeric(df["FISCAL_YEAR"], errors="coerce")

    add_flag(df["AMOUNT_num"] < 0, "amount_negative")
    add_flag(df["AMOUNT_num"] == 0, "amount_zero")
    add_flag(df["ITEM_DESCRIPTION"] == "", "item_description_missing")
    add_flag(df["BUDGET_PLAN"] == "", "budget_plan_missing")

    # CROSS_FUNC? ว่าง -> เติม 0 (ถือว่าไม่ใช่งบ cross-functional) + flag
    cf_blank = df["CROSS_FUNC?"] == ""
    df.loc[cf_blank, "CROSS_FUNC?"] = "0"
    add_flag(cf_blank, "cross_func_filled")

    # REF_PAGE_NO ไม่ใช่ตัวเลข -> flag (เก็บค่าเดิมไว้ใน quarantine)
    pg = pd.to_numeric(df["REF_PAGE_NO"], errors="coerce")
    pg_bad = pg.isna()
    add_flag(pg_bad, "ref_page_no_invalid")

    # แยกภาระผูกพันที่ปีนอกช่วง 2022-2026
    out_range = (df["OBLIGED?"] == "1") & (~df["YEAR_num"].isin(MAIN_YEARS))
    add_flag(out_range, "commitment_year_outside_range")
    add_flag(out_range & (df["YEAR_num"] <= 2021), "commitment_year_suspect_past")
    add_flag(out_range & (df["YEAR_num"] <= 2005), "commitment_year_impossible")

    # ministry ที่ map แบบอนุมาน (ใช้คอลัมน์ที่พกมาจากก่อน dedup)
    add_flag(df["_ministry_inferred"], "ministry_inferred")
    df.drop(columns=["_ministry_inferred"], inplace=True)
    # category ที่ยังแก้ไม่ได้
    add_flag((df["CATEGORY_LV1"] == "") & (df["ITEM_DESCRIPTION"] != ""), "category_lv1_unresolved")

    df["dq_flag"] = flags.map(lambda lst: ";".join(lst))

    main_df = df[~out_range].copy()
    comm_df = df[out_range].copy()
    note(f"  ไฟล์หลัก (ปี 2022-2026): {len(main_df):,} แถว")
    note(f"  ภาระผูกพัน (ปีนอกช่วง): {len(comm_df):,} แถว "
         f"(ปี <=2021 น่าสงสัย: {int((comm_df['YEAR_num'] <= 2021).sum()):,} แถว, ปี <=2005 เป็นไปไม่ได้: {int((comm_df['YEAR_num'] <= 2005).sum()):,} แถว)")

    # ---------- ขั้น 7: แปลงชนิดข้อมูล ----------
    for d in (main_df, comm_df):
        d["AMOUNT"] = d["AMOUNT_num"].astype("int64")
        d["FISCAL_YEAR"] = d["YEAR_num"].astype("int16")
        d["REF_PAGE_NO"] = pd.to_numeric(d["REF_PAGE_NO"], errors="coerce").astype("Int64")
        d["OBLIGED?"] = d["OBLIGED?"].map({"1": True, "0": False})
        d["CROSS_FUNC?"] = d["CROSS_FUNC?"].map({"1": True, "0": False})
        d.drop(columns=["AMOUNT_num", "YEAR_num"], inplace=True)

    # ---------- เขียน output ----------
    note("\n=== เขียนไฟล์ output ===")
    main_path = f"{OUTDIR}/budget_2566-2569_clean.csv.gz"
    comm_path = f"{OUTDIR}/budget_2566-2569_commitments.csv.gz"
    main_df.to_csv(main_path, index=False, compression="gzip")
    comm_df.to_csv(comm_path, index=False, compression="gzip")
    note(f"  {main_path}")
    note(f"  {comm_path}")

    # quarantine: แถวที่ต้องตรวจสอบด้วยมือ
    qmask = (df["dq_flag"].str.contains("commitment_year_impossible|amount_negative|"
                                       "item_description_missing|ref_page_no_invalid|"
                                       "category_lv1_unresolved", regex=True))
    q = df[qmask].copy()
    q_path = f"{OUTDIR}/quarantine_review.csv.gz"
    q.to_csv(q_path, index=False, compression="gzip")
    note(f"  {q_path} ({len(q):,} แถว)")

    # ---------- validation ----------
    note("\n=== ขั้น 7: ตรวจสอบยอดรวมก่อน-หลัง ===")
    clean_total = main_df.groupby("FISCAL_YEAR")["AMOUNT"].sum()
    for y in sorted(set(raw_total_by_year.index) & set(range(2022, 2027))):
        r = raw_total_by_year.get(y, 0)
        c = clean_total.get(y, 0)
        note(f"  ปี {y}: ดิบ {r/1e9:,.2f}B -> clean {c/1e9:,.2f}B (ต่าง { (c-r)/1e6:,.1f}M จากการลบซ้ำ)")
    note(f"  รวมทุกปีไฟล์หลัก: {main_df['AMOUNT'].sum()/1e9:,.2f}B")
    note(f"  รวมภาระผูกพัน: {comm_df['AMOUNT'].sum()/1e9:,.2f}B")

    # ---------- cleaning_summary.md ----------
    with open(f"{OUTDIR}/cleaning_summary.md", "w", encoding="utf-8") as f:
        f.write("# สรุปการ Clean ข้อมูล\n\n")
        f.write(f"- วันที่: 2026-10-09\n- Input: `{SRC}` ({n_raw:,} แถว)\n")
        f.write(f"- Output หลัก: `budget_2566-2569_clean.csv.gz` ({len(main_df):,} แถว, ปี 2022-2026)\n")
        f.write(f"- ภาระผูกพัน: `budget_2566-2569_commitments.csv.gz` ({len(comm_df):,} แถว)\n")
        f.write(f"- Quarantine: `quarantine_review.csv.gz` ({len(q):,} แถว)\n\n")
        f.write("## สิ่งที่ทำ\n\n")
        for line in log:
            f.write(line.replace("===", "###") + "\n")
        f.write("\n## ตาราง audit การแก้สะกด\n\n")
        f.write("| ประเภท | scope | rule | cells |\n|---|---|---|---|\n")
        for typ, scope, rule, n in fix_audit:
            f.write(f"| {typ} | {scope} | {rule} | {n:,} |\n")
        f.write("\n## Flag (dq_flag) ที่ติดในไฟล์ output\n\n")
        f.write("| flag | ความหมาย | จำนวน (ไฟล์หลัก+ผูกพัน) |\n|---|---|---|\n")
        allf = pd.concat([main_df, comm_df])
        for fl in ["amount_negative", "amount_zero", "item_description_missing",
                   "budget_plan_missing", "cross_func_filled", "ref_page_no_invalid",
                   "commitment_year_outside_range", "commitment_year_suspect_past",
                   "commitment_year_impossible", "ministry_inferred", "category_lv1_unresolved"]:
            f.write(f"| {fl} | - | {int(allf['dq_flag'].str.contains(fl).sum()):,} |\n")
        f.write("\n## สิ่งที่ยังไม่แก้ (เหลือเช็คกับต้นฉบับ)\n\n")
        f.write("- แถวภาระผูกพันปี <= 2021 (9,063 แถว) น่าจะเป็น artifact จากการแปลงไฟล์ (ปีในเอกสารไม่ควรย้อนหลัง) — อยู่ในไฟล์ commitments พร้อม flag\n")
        f.write("- รูปแบบเว้นวรรคบางแบบใน OUTPUT/PROJECT/ITEM_DESCRIPTION ที่ไม่มั่นใจว่าแบบไหนถูกต้อง (เช่น `การร่วมลงทุน ระหว่าง` vs `การร่วมลงทุนระหว่าง`) — ไม่แก้เพราะเดาไม่ได้\n")
        f.write("- คอลัมน์ OUTPUT/PROJECT/STRATEGY/MOTHER_PLAN ว่างค่อนข้างมาก — เป็นลักษณะโครงสร้างของข้อมูล ไม่ใช่ missing\n")
    note(f"  {OUTDIR}/cleaning_summary.md")

    print("\n🎉 เสร็จสิ้น")


